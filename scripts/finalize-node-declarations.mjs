import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const MARKER = '/* nemo-relay-json-types */';
const JSON_DECLARATIONS = `${MARKER}
/** One JSON scalar value accepted by the NeMo Relay runtime. */
export type JsonPrimitive = string | number | boolean | null
/** A JSON object with recursively JSON-serializable values. */
export interface JsonObject { [key: string]: Json }
/** A JSON array with recursively JSON-serializable values. */
export interface JsonArray extends Array<Json> {}
/** Any JSON-serializable value accepted by the NeMo Relay runtime. */
export type Json = JsonPrimitive | JsonObject | JsonArray

`;

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const defaultTarget = path.join(scriptDirectory, '..', 'crates', 'node', 'index.d.ts');
const target = process.argv[2] === undefined ? defaultTarget : path.resolve(process.argv[2]);
const declarations = readFileSync(target, 'utf8');

if (!declarations.includes(MARKER)) {
  const generatedHeader = '/* auto-generated by NAPI-RS */\n\n';
  const insertion = declarations.includes(generatedHeader)
    ? declarations.replace(generatedHeader, `${generatedHeader}${JSON_DECLARATIONS}`)
    : `${JSON_DECLARATIONS}${declarations}`;
  writeFileSync(target, insertion, 'utf8');
}
